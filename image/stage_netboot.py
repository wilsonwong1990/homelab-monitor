#!/usr/bin/env python3
"""Sync private release assets to a trusted LAN web root; never export credentials."""
import argparse
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

if __package__:
    from .assemble import assemble
    from .pxe import digest, render_menu, validate_url, verify_assets
else:
    from assemble import assemble
    from pxe import digest, render_menu, validate_url, verify_assets

MARKER = "# Generated by homelab-monitor; credentials stay on the staging host.\n"
PXE_NAMES = {"pxe-vmlinuz", "pxe-initrd", "homelab.ipxe", "PXE-SHA256SUMS", "SHA256SUMS", "provenance.json"}


def gh(*arguments):
    return subprocess.check_output(["gh", *arguments], text=True)


def latest_ubuntu(repo):
    pages = json.loads(gh("api", "--paginate", "--slurp", f"repos/{repo}/releases?per_page=100"))
    releases = [release for page in pages for release in page
                if not release["draft"] and not release["prerelease"]
                and re.fullmatch(r"ubuntu-24\.04\.[0-9]+(?:\.[0-9]+)?-[0-9a-f]{12}-[0-9a-f]{12}", release["tag_name"])]
    if not releases:
        raise ValueError("no published production Ubuntu refresh release; specify --tag for another release")
    return max(releases, key=lambda release: release["published_at"])["tag_name"]


def download(repo, tag, destination):
    release = json.loads(gh("release", "view", tag, "--repo", repo, "--json", "isDraft,assets"))
    if release["isDraft"]:
        raise ValueError("refusing unpublished draft release")
    parts = {asset["name"] for asset in release["assets"]
             if re.fullmatch(r"homelab-monitor-[0-9a-f]{12}\.iso\.part[0-9]{3}", asset["name"])}
    names = {asset["name"] for asset in release["assets"]}
    if not parts or not PXE_NAMES <= names:
        raise ValueError("release lacks ISO parts or required PXE metadata/assets")
    args = ["release", "download", tag, "--repo", repo, "--dir", str(destination)]
    for name in sorted(parts | PXE_NAMES):
        args.extend(("--pattern", name))
    gh(*args)


def verify_release(directory):
    metadata = json.loads((directory / "provenance.json").read_text())
    if not re.fullmatch(r"[0-9a-f]{40}", metadata["source_commit"]):
        raise ValueError("invalid source commit")
    verify_assets(directory)
    if metadata["pxe"] != {name: digest(directory / name) for name in ("pxe-vmlinuz", "pxe-initrd", "homelab.ipxe")}:
        raise ValueError("PXE assets disagree with image provenance")
    image, sha = assemble(directory, True)
    if metadata["image"] != image or metadata["image_sha256"] != sha:
        raise ValueError("ISO disagrees with provenance")
    return image, sha


def stage(directory, web_root, base_url, tag):
    base_url = validate_url(base_url)
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,150}", tag):
        raise ValueError("invalid release tag for LAN path")
    if not web_root.is_dir():
        raise ValueError("--web-root must be an existing dedicated web directory")
    root = web_root.resolve()
    release_root = root / "homelab"
    if release_root.is_symlink():
        raise ValueError("release directory must not be a symlink")
    release_root.mkdir(exist_ok=True)
    lock = root / ".homelab-sync-lock"
    lock.mkdir()  # A concurrent sync fails explicitly; the next scheduled run can retry.
    try:
        image, sha = verify_release(directory)
        destination = release_root / tag
        checksums = {
            "installer.iso": sha,
            "vmlinuz": digest(directory / "pxe-vmlinuz"),
            "initrd": digest(directory / "pxe-initrd"),
            "homelab.ipxe": digest(directory / "homelab.ipxe"),
            "provenance.json": digest(directory / "provenance.json"),
        }
        menu = MARKER + render_menu(f"{base_url}/homelab/{tag}")
        if destination.exists() or destination.is_symlink():
            if destination.is_symlink() or not destination.is_dir():
                raise ValueError("invalid existing release directory")
            for name, expected in checksums.items():
                if digest(destination / name) != expected:
                    raise ValueError("staged release differs or is corrupt; refusing to overwrite")
        else:
            # Assemble outside the web root; failed checks never publish partial boot assets.
            if (directory / image).exists():
                if digest(directory / image) != sha:
                    raise ValueError("existing reconstructed ISO is corrupt")
            else:
                assemble(directory)
            with tempfile.TemporaryDirectory(prefix=".homelab-stage-", dir=root) as temp:
                output = Path(temp) / "ready"
                output.mkdir()
                for source, name in ((image, "installer.iso"), ("pxe-vmlinuz", "vmlinuz"),
                                     ("pxe-initrd", "initrd"), ("homelab.ipxe", "homelab.ipxe"),
                                     ("provenance.json", "provenance.json")):
                    shutil.copyfile(directory / source, output / name)
                    (output / name).chmod(0o644)
                (output / "boot.ipxe").write_text(menu)
                (output / "boot.ipxe").chmod(0o644)
                output.chmod(0o755)
                output.rename(destination)
        current = root / "homelab.ipxe"
        if current.is_symlink() or (current.exists() and not current.read_text().startswith(MARKER)):
            raise ValueError("refusing to overwrite an unrelated homelab.ipxe")
        with tempfile.NamedTemporaryFile(mode="w", prefix=".homelab-menu-", dir=root, delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(menu)
        try:
            temporary.chmod(0o644)
            temporary.replace(current)
        finally:
            temporary.unlink(missing_ok=True)
        print(f"PASS: staged {tag}; netboot.xyz chain URL: {base_url}/homelab.ipxe")
    finally:
        lock.rmdir()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default="wilsonwong1990/homelab-monitor")
    tags = parser.add_mutually_exclusive_group(required=True)
    tags.add_argument("--tag", help="explicit published release, including a validation prerelease")
    tags.add_argument("--latest-ubuntu", action="store_true", help="newest published production Ubuntu refresh")
    parser.add_argument("--web-root", type=Path, required=True)
    parser.add_argument("--base-url", required=True, help="LAN URL corresponding to --web-root")
    parser.add_argument("--from-directory", type=Path, help="use already-downloaded assets (no GitHub call)")
    args = parser.parse_args()
    validate_url(args.base_url)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.repo):
        parser.error("invalid owner/repository")
    if args.from_directory and args.latest_ubuntu:
        parser.error("--from-directory requires an explicit --tag")
    tag = latest_ubuntu(args.repo) if args.latest_ubuntu else args.tag
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,150}", tag):
        parser.error("invalid release tag")
    if args.from_directory:
        stage(args.from_directory, args.web_root, args.base_url, tag)
    else:
        # gh auth state and download cache remain outside the served directory.
        with tempfile.TemporaryDirectory(prefix="homelab-download-") as temp:
            download(args.repo, tag, Path(temp))
            stage(Path(temp), args.web_root, args.base_url, tag)


if __name__ == "__main__":
    main()
