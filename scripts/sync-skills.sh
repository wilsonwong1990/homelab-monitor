#!/usr/bin/env bash
# Vendor the canonical skills the monitor reads from homelab-assistant-agent.
# Skills are edited only upstream; this copies them at a pinned commit so that
# releases, git archive and the installer image stay self-contained.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/skills"
SKILLS=(monitoring proxmox unifi)
SOURCE="https://github.com/wilsonwong1990/homelab-assistant-agent.git"
REF=""
CHECK=0

usage() {
  cat <<USAGE
Usage: scripts/sync-skills.sh [--ref COMMIT_OR_BRANCH] [--source GIT_URL_OR_PATH] [--check]

  --ref     Upstream commit or branch to vendor (default: the pinned commit in skills/SOURCE)
  --source  Upstream repository (default: $SOURCE)
  --check   Verify vendored skills match the pinned commit; change nothing
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --ref) REF="${2:?--ref needs a value}"; shift 2 ;;
    --source) SOURCE="${2:?--source needs a value}"; shift 2 ;;
    --check) CHECK=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
done

if [[ -z "$REF" ]]; then
  [[ -f "$DEST/SOURCE" ]] || { echo "ERROR: no --ref given and $DEST/SOURCE missing" >&2; exit 1; }
  REF="$(sed -n 's/^commit=//p' "$DEST/SOURCE")"
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git init -q "$tmp/src"
git -C "$tmp/src" fetch -q --depth 1 "$SOURCE" "$REF"
sha="$(git -C "$tmp/src" rev-parse FETCH_HEAD)"

stage="$tmp/skills"
mkdir -p "$stage"
for skill in "${SKILLS[@]}"; do
  mkdir -p "$stage/$skill"
  git -C "$tmp/src" show "$sha:.github/skills/$skill/SKILL.md" > "$stage/$skill/SKILL.md"
done
printf '%s\n' "# Generated by scripts/sync-skills.sh; edit skills upstream, not here." \
  "repository=${SOURCE%.git}" "commit=$sha" > "$stage/SOURCE"

if [[ $CHECK -eq 1 ]]; then
  if diff -r "$stage" "$DEST" >/dev/null; then
    echo "vendored skills match $sha"
  else
    diff -ru "$DEST" "$stage" || true
    echo "ERROR: skills/ differs from upstream $sha; run scripts/sync-skills.sh --ref $sha" >&2
    exit 1
  fi
  exit 0
fi

rm -rf "$DEST"
mv "$stage" "$DEST"
echo "vendored ${SKILLS[*]} from $sha"
